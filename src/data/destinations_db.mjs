/**
 * Resolves destination flag, city, and country.
 * Returns formatted label, e.g. "🇲🇳 Ulaanbaatar Mongolia".
 */
export function getDestinationDisplay(iataCode, matchMeta = {}) {
  const code = String(iataCode || '').trim().toUpperCase();
  const entry = DESTINATIONS_META[code];
  if (entry) {
    return {
      flag: entry.flag,
      city: entry.city,
      country: entry.country,
      label: `${entry.flag} ${entry.city} ${entry.country}`,
    };
  }

  // Fallback if match metadata provides city/country
  const fallbackCity = matchMeta.destinationCity || matchMeta.city || code;
  const fallbackCountry = matchMeta.destinationCountry || matchMeta.country || '';
  const countryPart = fallbackCountry ? ` ${fallbackCountry}` : '';
  return {
    flag: '✈️',
    city: fallbackCity,
    country: fallbackCountry,
    label: `✈️ ${fallbackCity}${countryPart}`,
  };
}
